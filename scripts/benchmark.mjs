#!/usr/bin/env node
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

import {
  ClaudeMemAdapter,
  Fts5SemanticSearcher,
  TreMemRepo,
  migrate,
  searchBranchContext,
} from '../dist/index.js';

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO_ROOT = resolve(HERE, '..');
const OUT_PATH = resolve(REPO_ROOT, 'BENCHMARK.md');

const PROJECT = process.env.TRE_BENCH_PROJECT ?? 'tre-mem';
const BRANCH = process.env.TRE_BENCH_BRANCH ?? 'main';
const K = Number(process.env.TRE_BENCH_K ?? '10');

const QUERIES = [
  'FTS5 BM25 semantic searcher',
  'git reflog backfill branch',
  'MCP server stdio tool',
  'weighted rerank signal',
  'session-start hook claude code',
  'pin graduate fact',
  'claude-mem adapter readonly',
  'branch_tag schema migration',
  'epoch normalization milliseconds',
  'test fixture vitest',
];

function jaccard(a, b) {
  const A = new Set(a);
  const B = new Set(b);
  if (A.size === 0 && B.size === 0) return 1;
  let inter = 0;
  for (const x of A) if (B.has(x)) inter++;
  const union = A.size + B.size - inter;
  return union === 0 ? 1 : inter / union;
}

function precisionAtKByBranch(ids, branchTagsById, targetBranch) {
  if (ids.length === 0) return 0;
  let match = 0;
  for (const id of ids) {
    if (branchTagsById.get(id) === targetBranch) match++;
  }
  return match / ids.length;
}

function fmt(n, digits = 3) {
  return Number.isFinite(n) ? n.toFixed(digits) : 'n/a';
}

function main() {
  migrate();
  const adapter = new ClaudeMemAdapter();
  const repo = new TreMemRepo();
  try {
    const tags = repo.listBranchTagsForBranch(PROJECT, BRANCH, 100_000);
    const branchTagsById = new Map();
    for (const t of tags) branchTagsById.set(t.observation_id, t.branch);
    const totalBranchTagged = tags.length;

    const baselineSearcher = new Fts5SemanticSearcher(adapter);

    const rows = [];
    let sumPrecA = 0;
    let sumPrecB = 0;
    let sumJaccard = 0;
    let nonEmpty = 0;

    for (const q of QUERIES) {
      const a = baselineSearcher.search({ query: q, project: PROJECT, k: K });
      const aIds = a.map((h) => h.observationId);

      const b = searchBranchContext(
        { adapter, repo },
        { query: q, project: PROJECT, branch: BRANCH, k: K },
      );
      const bIds = b.map((h) => h.observation.id);

      const pA = precisionAtKByBranch(aIds, branchTagsById, BRANCH);
      const pB = precisionAtKByBranch(bIds, branchTagsById, BRANCH);
      const j = jaccard(aIds, bIds);

      const topBreak = b[0]?.breakdown;
      rows.push({
        query: q,
        aCount: aIds.length,
        bCount: bIds.length,
        pA,
        pB,
        j,
        topTotal: b[0]?.total,
        topBreak,
      });

      if (aIds.length > 0 || bIds.length > 0) {
        sumPrecA += pA;
        sumPrecB += pB;
        sumJaccard += j;
        nonEmpty++;
      }
    }

    const meanPrecA = nonEmpty > 0 ? sumPrecA / nonEmpty : 0;
    const meanPrecB = nonEmpty > 0 ? sumPrecB / nonEmpty : 0;
    const meanJaccard = nonEmpty > 0 ? sumJaccard / nonEmpty : 0;

    const distinctBranchTags = new Set(tags.map((t) => t.branch)).size;

    const lines = [];
    lines.push('# tre-mem — A/B Precision Benchmark');
    lines.push('');
    lines.push(`> Generated by \`node scripts/benchmark.mjs\``);
    lines.push('');
    lines.push('## Configuration');
    lines.push('');
    lines.push(`- Project: \`${PROJECT}\``);
    lines.push(`- Target branch: \`${BRANCH}\``);
    lines.push(`- Top-K: ${K}`);
    lines.push(`- Queries: ${QUERIES.length}`);
    lines.push(
      `- Branch-tagged observations on \`${BRANCH}\`: **${totalBranchTagged}** (distinct branches in project: ${distinctBranchTags})`,
    );
    lines.push('');
    lines.push('## Methodology');
    lines.push('');
    lines.push(
      '- **Baseline (A)** — `Fts5SemanticSearcher` over `~/.claude-mem/claude-mem.db` (`observations_fts`, BM25 ranked). This is the closest in-process proxy for raw `claude-mem.search` since claude-mem itself indexes via the same FTS5 table.',
    );
    lines.push(
      '- **tre-mem (B)** — `searchBranchContext` (3-signal weighted rerank: semantic + branch + recency, plus pin boost).',
    );
    lines.push('- For each query we record the top-K ids returned by A and B, then compute:');
    lines.push(
      '  - `precision@K_branch` — fraction of top-K observations whose `branch_tag.branch` equals the target branch.',
    );
    lines.push('  - `jaccard(A,B)` — overlap of the two top-K id sets.');
    lines.push(
      '  - B-top-1 score breakdown (`semantic / branch / recency / pin`) to show where rank came from.',
    );
    lines.push('');
    lines.push('## Per-query results');
    lines.push('');
    lines.push(
      '| Query | A hits | B hits | A precision@K | B precision@K | Jaccard | B top-1 total | B top-1 breakdown |',
    );
    lines.push('|---|---:|---:|---:|---:|---:|---:|---|');
    for (const r of rows) {
      const br = r.topBreak;
      const brStr = br
        ? `sem ${fmt(br.semantic, 2)} / br ${fmt(br.branch, 2)} / rec ${fmt(br.recency, 2)} / pin ${fmt(br.pin, 2)}`
        : 'n/a';
      lines.push(
        `| \`${r.query}\` | ${r.aCount} | ${r.bCount} | ${fmt(r.pA)} | ${fmt(r.pB)} | ${fmt(r.j)} | ${r.topTotal !== undefined ? fmt(r.topTotal) : 'n/a'} | ${brStr} |`,
      );
    }
    lines.push('');
    lines.push('## Aggregate');
    lines.push('');
    lines.push(`- Mean A precision@${K} = **${fmt(meanPrecA)}**`);
    lines.push(`- Mean B precision@${K} = **${fmt(meanPrecB)}**`);
    lines.push(`- Mean Jaccard(A, B) = **${fmt(meanJaccard)}**`);
    lines.push('');
    lines.push('## Interpretation');
    lines.push('');
    lines.push(
      `> Precision delta (B − A) reflects how much the 3-signal rerank concentrates branch-tagged observations at the top of results versus a pure semantic baseline. Higher B precision means tre-mem successfully surfaces observations that are known to belong to the working branch (and, in a multi-branch dataset, suppresses off-branch noise). Jaccard < 1 means tre-mem actively re-orders / re-selects vs baseline (Jaccard = 1 would mean rerank is a no-op).`,
    );
    if (distinctBranchTags <= 1) {
      lines.push('');
      lines.push(
        `> **Single-branch dataset note:** \`${PROJECT}\` currently only has observations on \`${BRANCH}\` (${distinctBranchTags} distinct branch). The precision metric here therefore reduces to "fraction of top-K that are branch-tagged"; once a second branch is backfilled, the same harness will additionally measure cross-branch precision (off-branch tags will count as misses).`,
      );
    }
    lines.push('');
    lines.push(
      '_Reproduce: `pnpm build && node scripts/benchmark.mjs` (env: `TRE_BENCH_PROJECT`, `TRE_BENCH_BRANCH`, `TRE_BENCH_K`)._',
    );
    lines.push('');

    mkdirSync(dirname(OUT_PATH), { recursive: true });
    writeFileSync(OUT_PATH, lines.join('\n'));

    process.stdout.write(
      `wrote ${OUT_PATH}\n  meanPrecA=${fmt(meanPrecA)} meanPrecB=${fmt(meanPrecB)} meanJaccard=${fmt(meanJaccard)}\n`,
    );
  } finally {
    adapter.close();
    repo.close();
  }
}

main();
